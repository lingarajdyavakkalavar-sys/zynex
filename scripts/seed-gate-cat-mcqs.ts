import { PrismaClient } from '@prisma/client';

const prisma = new PrismaClient();

type MCQ = {
  question: string;
  options: { index: number; text: string }[];
  correctAnswer: number;
  explanation?: string;
  marks: number;
  negativeMarks: number;
  difficulty: string;
  gateTopicId?: string;
  catTopicId?: string;
  gateBranchCode?: string;
  catSectionCode?: string;
  tags: string[];
};

async function clearMCQs() {
  await prisma.mCQAttempt.deleteMany({});
  await prisma.mCQ.deleteMany({});
  console.log('Cleared existing MCQs and attempts');
}

async function seedMCQs(mcqs: MCQ[]) {
  let saved = 0;
  let failed = 0;

  for (const mcq of mcqs) {
    try {
      await prisma.mCQ.create({
        data: {
          question: mcq.question,
          options: mcq.options,
          correctAnswer: mcq.correctAnswer,
          explanation: mcq.explanation || null,
          difficulty: mcq.difficulty as any,
          examType: 'GATE',
          marks: mcq.marks,
          negativeMarks: mcq.negativeMarks,
          gateTopicId: mcq.gateTopicId || null,
          catTopicId: mcq.catTopicId || null,
          gateBranchCode: mcq.gateBranchCode || null,
          catSectionCode: mcq.catSectionCode || null,
          sourceType: 'OFFICIAL_PAPER' as any,
          isPreviousYear: true,
          tags: mcq.tags,
        },
      });
      saved++;
    } catch (err) {
      console.error('Failed:', err);
      failed++;
    }
  }

  console.log(`Saved: ${saved}, Failed: ${failed}`);
  return { saved, failed };
}

