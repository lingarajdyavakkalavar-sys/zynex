async function main() {
  console.log('Starting comprehensive MCQ seeding...\n');

  await clearMCQs();

  console.log('Seeding GATE CS questions...');
  const csResult = await seedMCQs(GATE_CS_QUESTIONS);

  console.log('\nSeeding GATE EC questions...');
  const ecResult = await seedMCQs(GATE_EC_QUESTIONS);

  console.log('\nSeeding GATE EE questions...');
  const eeResult = await seedMCQs(GATE_EE_QUESTIONS);

  console.log('\nSeeding GATE ME questions...');
  const meResult = await seedMCQs(GATE_ME_QUESTIONS);

  console.log('\nSeeding GATE CE questions...');
  const ceResult = await seedMCQs(GATE_CE_QUESTIONS);

  console.log('\nSeeding CAT questions...');
  const catMCQs = CAT_QUESTIONS.map(q => ({
    ...q,
    examType: 'CAT' as const,
  }));

  for (const mcq of catMCQs) {
    try {
      await prisma.mCQ.create({
        data: {
          question: mcq.question,
          options: mcq.options,
          correctAnswer: mcq.correctAnswer,
          explanation: mcq.explanation || null,
          difficulty: mcq.difficulty as any,
          examType: 'CAT',
          marks: 1,
          negativeMarks: 0,
          catSectionCode: mcq.catSectionCode || null,
          sourceType: 'OFFICIAL_PAPER' as any,
          isPreviousYear: true,
          tags: mcq.tags,
        },
      });
    } catch (err) {
      console.error('CAT MCQ failed:', err);
    }
  }

  const totalGATE = csResult.saved + ecResult.saved + eeResult.saved + meResult.saved + ceResult.saved;
  const totalCAT = CAT_QUESTIONS.length;

  console.log('\n=== Seed Summary ===');
  console.log(`GATE CS: ${csResult.saved} questions`);
  console.log(`GATE EC: ${ecResult.saved} questions`);
  console.log(`GATE EE: ${eeResult.saved} questions`);
  console.log(`GATE ME: ${meResult.saved} questions`);
  console.log(`GATE CE: ${ceResult.saved} questions`);
  console.log(`CAT: ${totalCAT} questions`);
  console.log(`TOTAL: ${totalGATE + totalCAT} questions`);

  await prisma.$disconnect();
}

main().catch(console.error);